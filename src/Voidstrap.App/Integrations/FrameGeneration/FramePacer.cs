        public double ConsumeRatioEma;
    }

    [StructLayout(LayoutKind.Sequential)]
    internal struct PacerCadenceInput
    {
        public double Dt;
        public double CapMs;
        public double CaptureGapEma;
        public long SkippedSinceLastUse;
        public int FpsCap;
