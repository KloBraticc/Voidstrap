    internal static unsafe partial class FramePacer
    {
        private const uint AbiVersion = 2;
        private const string Library = "voidpacer";
        private static int _state;
        private static string _failure = "";

        public const uint EventFastFlowCapture = 1;
        public const uint EventLowerQualityCapture = 2;
        public const uint EventSixLowerCapture = 3;
        public const uint EventAutoLowerCapture = 4;
        public const uint EventAutoRestoreQuiet = 5;
        public const uint EventFastFlowPacing = 6;
        public const uint EventLowerQualityPacing = 7;
        public const uint EventSixLowerPacing = 8;
        public const uint EventAutoLowerPacing = 9;
        public const uint EventAutoRestoreStable = 10;
        public const uint EventSixRestoreStable = 11;
        public const uint EventRaiseQualityTop = 12;
        public const uint EventRaiseQuality = 13;

        [StructLayout(LayoutKind.Sequential)]
        private struct Layout
        {
            public uint AbiVersion;
            public uint Cadence;
            public uint CadenceInput;
            public uint CadenceResult;
            public uint Aligner;
            public uint Quality;
        }

        public static string Failure => _failure;

        public static bool Available
        {
            get
            {
                if (_state == 0)
                    _state = Probe() ? 1 : 2;
                return _state == 1;
            }
        }

        private static bool Probe()
        {
            try
            {
                Layout layout = vfp_layout();
                if (layout.AbiVersion != AbiVersion
                    || layout.Cadence != sizeof(PacerCadence)
                    || layout.CadenceInput != sizeof(PacerCadenceInput)
                    || layout.CadenceResult != sizeof(PacerCadenceResult)
                    || layout.Aligner != sizeof(PacerAligner)
                    || layout.Quality != sizeof(PacerQuality))
                {
                    _failure = "the frame pacer library does not match this version of Voidstrap";
                    return false;
                }
                return true;
            }
            catch (Exception ex) when (ex is DllNotFoundException or EntryPointNotFoundException or BadImageFormatException)
            {
                _failure = "the frame pacer library could not be loaded: " + ex.Message;
                return false;
            }
        }

        public static PacerCadenceResult UpdateCadence(ref PacerCadence cadence, in PacerCadenceInput input)
        {
            PacerCadenceResult result;
            fixed (PacerCadence* state = &cadence)
            fixed (PacerCadenceInput* source = &input)
                vfp_cadence_update(state, source, &result);
            return result;
        }

        public static double Align(ref PacerAligner aligner, double targetMs, double slotMs, double refreshHz)
        {
            fixed (PacerAligner* state = &aligner)
                return vfp_align(state, targetMs, slotMs, refreshHz);
        }

        public static void RecordSlot(ref PacerQuality quality, bool missed, double nowSec)
        {
            fixed (PacerQuality* state = &quality)
                vfp_quality_record_slot(state, missed ? 1 : 0, nowSec);
        }

        public static uint ConsiderQuality(ref PacerQuality quality, int minimumQuality, bool captureBackpressure, int activeMode, int currentGenerated, double nowSec)
        {
            fixed (PacerQuality* state = &quality)
                return vfp_quality_consider(state, minimumQuality, captureBackpressure ? 1 : 0, activeMode, currentGenerated, nowSec);
        }

        public static int SourceHealth(ref PacerQuality quality, double baseFps, double nowSec)
        {
            fixed (PacerQuality* state = &quality)
                return vfp_quality_source_health(state, baseFps, nowSec);
        }

        public static int TargetTotal(double frameMs, double refreshHz, int mode, bool uncap, ref double phase)
        {
            fixed (double* value = &phase)
                return vfp_target_total(frameMs, refreshHz, mode, uncap ? 1 : 0, value);
        }

        public static double MedianInterval(ReadOnlySpan<double> samples)
        {
            fixed (double* values = samples)
                return vfp_median_interval(values, samples.Length);
        }

        [LibraryImport(Library)]
        private static partial Layout vfp_layout();

        [LibraryImport(Library)]
        private static partial int vfp_cadence_update(PacerCadence* state, PacerCadenceInput* input, PacerCadenceResult* result);

        [LibraryImport(Library)]
        private static partial double vfp_align(PacerAligner* state, double targetMs, double slotMs, double refreshHz);

        [LibraryImport(Library)]
        private static partial void vfp_quality_record_slot(PacerQuality* state, int missed, double nowSec);

        [LibraryImport(Library)]
        private static partial uint vfp_quality_consider(PacerQuality* state, int minimumQuality, int captureBackpressure, int activeMode, int currentGenerated, double nowSec);

        [LibraryImport(Library)]
        private static partial int vfp_quality_source_health(PacerQuality* state, double baseFps, double nowSec);

        [LibraryImport(Library)]
        private static partial int vfp_target_total(double frameMs, double refreshHz, int mode, int uncap, double* phase);

        [LibraryImport(Library)]
        internal static partial int vfp_max_generated_for(int mode);

        [LibraryImport(Library)]
        internal static partial int vfp_max_generated_for_cadence(int mode, double consumeRatio);

        [LibraryImport(Library)]
        internal static partial int vfp_required_cadence_samples(double frameMs);

        [LibraryImport(Library)]
        internal static partial int vfp_first_unshown_slot(int filled, int total);

        [LibraryImport(Library)]
        internal static partial double vfp_normalize_interval(double measuredMs, double expectedMs);

        [LibraryImport(Library)]
        private static partial double vfp_median_interval(double* samples, int count);

        [LibraryImport(Library)]
        internal static partial int vfp_is_slot_overdue(double targetMs, double nowMs, double slotMs);

        [LibraryImport(Library)]
        internal static partial int vfp_is_source_stutter(double elapsedMs, double expectedMs);

        [LibraryImport(Library)]
        internal static partial double vfp_output_slot_ms(double sourceIntervalMs, double refreshHz, int total, int uncap);
    }
}
